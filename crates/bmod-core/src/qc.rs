//! QC script generation for a static prop.

pub struct QcParams<'a> {
    /// Path relative to `models/`, e.g. `bmod/crate.mdl`.
    pub model_path: &'a str,
    /// Directory relative to `materials/`, e.g. `models/bmod/crate/`.
    pub cdmaterials: &'a str,
    pub reference_smd: &'a str,
    pub physics_smd: &'a str,
    pub surfaceprop: &'a str,
    /// Number of convex pieces in a concave collision model; `None` for a single hull.
    pub concave_pieces: Option<usize>,
}

pub fn generate(p: &QcParams) -> String {
    // Without $concave, studiomdl wraps the whole physics mesh in one hull.
    let concave = match p.concave_pieces {
        Some(n) => format!("\t$concave\n\t$maxconvexpieces {n}\n"),
        None => String::new(),
    };
    format!(
        "// Generated by BMod\n\
         $modelname \"{model}\"\n\
         $staticprop\n\
         $body \"body\" \"{reference}\"\n\
         $cdmaterials \"{cdmaterials}\"\n\
         $surfaceprop \"{surfaceprop}\"\n\
         $sequence \"idle\" \"{reference}\"\n\
         $collisionmodel \"{physics}\"\n\
         {{\n\
         {concave}\
         \t$automass\n\
         }}\n",
        model = p.model_path,
        reference = p.reference_smd,
        physics = p.physics_smd,
        cdmaterials = p.cdmaterials,
        surfaceprop = p.surfaceprop,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn params(concave_pieces: Option<usize>) -> QcParams<'static> {
        QcParams {
            model_path: "bmod/cup.mdl",
            cdmaterials: "models/bmod/cup/",
            reference_smd: "cup_ref.smd",
            physics_smd: "cup_phys.smd",
            surfaceprop: "default",
            concave_pieces,
        }
    }

    #[test]
    fn convex_collision_block() {
        assert!(generate(&params(None)).ends_with("$collisionmodel \"cup_phys.smd\"\n{\n\t$automass\n}\n"));
    }

    #[test]
    fn concave_collision_block() {
        assert!(generate(&params(Some(7))).ends_with(
            "$collisionmodel \"cup_phys.smd\"\n{\n\t$concave\n\t$maxconvexpieces 7\n\t$automass\n}\n"
        ));
    }
}
